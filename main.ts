// free-model-aggregator-02 — one server, two client wires, one real free model behind
// every answer.
//
// The server reads the trial brief (MAKEFUN_PROMPT_FILE), registers its port and catalog
// with the env (MAKEFUN_ENV_URL), and answers the six prompts the env sends — three on the
// OpenAI wire (POST /v1/chat/completions), three on the Anthropic wire (POST /v1/messages) —
// by dialling a real OpenRouter free model through the grader's gateway
// (POST $OPENAI_BASE_URL/chat/completions). It never answers from itself.
//
// Routing: for each prompt, rank the brief's free models by rating_milli (highest first,
// brief order breaks ties) among the models that meet the prompt's requirements (JSON mode,
// tools, vision), and dial the best. On a refusal (4xx/5xx or a dropped call) it retries
// the best model once, then fails over to the next-best eligible model, up to four calls
// per prompt. A model that refuses is cooled down for the rest of the trial, so one
// rate-limited model cannot take later prompts down with it. Every refusal is reported
// on the served answer in the x-makefun-upstream-failures header, the only way the
// failover column can see a recovered refusal.
//
// Everything is a pure function of the brief, the requests and the gateway's answers:
// no wall clock and no unseeded randomness, so a replay leaves the same state export.
// Model lists use fixed timestamps for the same reason.
//
// Run it outside a trial with `node main.ts --list` to print the catalog document and
// exit 0. With no brief it prints an empty catalog and exits 0.

