function sseEvent(event: string | null, data: unknown): string {
  return `${event === null ? '' : `event: ${event}\n`}data: ${JSON.stringify(data)}\n\n`;
}

/** One SSE frame with every data payload's `model` set to `model`. A provider may repeat
 *  the finish reason on the usage chunk that follows the last content chunk; the wire
 *  carries exactly one finish chunk, so only the first chunk to name one keeps it and
 *  later ones have it nulled (their usage survives). */
function frameWithModel(frame: string, model: string, streamState: { finishSeen: boolean }): string {
  const lines = frame.split('\n').map((line) => {
    const trimmed = line.trim();
    if (!trimmed.startsWith('data:')) return line;
    const payload = trimmed.slice(5).trim();
    if (payload === '' || payload === '[DONE]') return line;
    try {
      const chunk: unknown = JSON.parse(payload);
      if (isRecord(chunk)) {
        const out: Json = { ...chunk, model };
        const choices = Array.isArray(out.choices) ? out.choices : [];
        out.choices = choices.map((c) => {
          if (!isRecord(c) || c.finish_reason === null || c.finish_reason === undefined) return c;
          if (streamState.finishSeen) return { ...c, finish_reason: null };
          streamState.finishSeen = true;
          return c;
        });
        return `data: ${JSON.stringify(out)}`;
      }
    } catch {
      // Not JSON: relay the line as it came.
    }
    return line;
  });
  return `${lines.join('\n')}\n\n`;
}

/** A Chat Completions SSE stream, frame by frame, every chunk's `model` the id dialled. */
async function* openAIStreamWithModel(upstream: ReadableStream<Uint8Array>, model: string): AsyncGenerator<string> {
  const reader = upstream.getReader();
  const decoder = new TextDecoder();
  let buffer = '';
  const streamState = { finishSeen: false };
  try {
    for (;;) {
      const { value, done } = await reader.read();
      if (done) break;
      buffer += decoder.decode(value, { stream: true }).replace(/\r\n/g, '\n');
      let at = buffer.indexOf('\n\n');
      while (at !== -1) {
        const frame = buffer.slice(0, at);
        buffer = buffer.slice(at + 2);
        yield frameWithModel(frame, model, streamState);
        at = buffer.indexOf('\n\n');
      }
    }
    buffer += decoder.decode();
    if (buffer.trim() !== '') yield frameWithModel(buffer, model, streamState);
  } finally {
    reader.releaseLock();
  }
}

/** A Chat Completions SSE stream as the Anthropic event sequence. */
async function* anthropicEventsFromOpenAI(upstream: ReadableStream<Uint8Array>, model: string): AsyncGenerator<string> {
  const reader = upstream.getReader();
  const decoder = new TextDecoder();
  let buffer = '';
  let started = false;
  let finished = false;
  let pendingStop: string | null = null;
  let textIndex = -1;
  let nextIndex = 0;
  const toolIndexes = new Map<number, number>();
  let inputTokens = 0;
  let outputTokens = 0;

  const startEvents = (): string[] => {
    if (started) return [];
    started = true;
    return [
      sseEvent('message_start', {
        type: 'message_start',
        message: {
          id: 'msg_stream',
          type: 'message',
          role: 'assistant',
          model,
          content: [],
          stop_reason: null,
          stop_sequence: null,
          usage: { input_tokens: inputTokens, output_tokens: 0 },
        },
      }),
    ];
  };
  const closeEvents = (): string[] => {
    const out: string[] = [];
    if (textIndex !== -1) {
      out.push(sseEvent('content_block_stop', { type: 'content_block_stop', index: textIndex }));
      textIndex = -1;
    }
    for (const index of [...toolIndexes.values()].sort((a, b) => a - b)) out.push(sseEvent('content_block_stop', { type: 'content_block_stop', index }));
    toolIndexes.clear();
    return out;
  };
  const finishEvents = (stopReason: string): string[] => {
    if (finished) return [];
    finished = true;
    return [
      ...closeEvents(),
      sseEvent('message_delta', { type: 'message_delta', delta: { stop_reason: stopReason, stop_sequence: null }, usage: { output_tokens: outputTokens } }),
      sseEvent('message_stop', { type: 'message_stop' }),
    ];
  };

  const eventsOfFrame = (frame: string): string[] => {
    const out: string[] = [];
    for (const line of frame.split('\n')) {
      const trimmed = line.trim();
      if (!trimmed.startsWith('data:')) continue;
      const payload = trimmed.slice(5).trim();
      if (payload === '[DONE]') {
        out.push(...startEvents(), ...finishEvents(pendingStop ?? 'end_turn'));
        continue;
      }
      let chunk: unknown;
      try {
        chunk = JSON.parse(payload);
      } catch {
        continue;
      }
      if (!isRecord(chunk)) continue;
      if (isRecord(chunk.usage)) {
        inputTokens = numberOrZero(chunk.usage.prompt_tokens);
        outputTokens = numberOrZero(chunk.usage.completion_tokens);
      }
      const choices = Array.isArray(chunk.choices) ? chunk.choices : [];
      const choice = isRecord(choices[0]) ? choices[0] : null;
      if (choice === null) continue;
      const delta = isRecord(choice.delta) ? choice.delta : {};
      out.push(...startEvents());
      if (typeof delta.content === 'string' && delta.content !== '') {
        if (textIndex === -1) {
          textIndex = nextIndex;
          nextIndex += 1;
          out.push(sseEvent('content_block_start', { type: 'content_block_start', index: textIndex, content_block: { type: 'text', text: '' } }));
        }
        out.push(sseEvent('content_block_delta', { type: 'content_block_delta', index: textIndex, delta: { type: 'text_delta', text: delta.content } }));
      }
      const calls = Array.isArray(delta.tool_calls) ? delta.tool_calls : [];
      for (const call of calls) {
        if (!isRecord(call)) continue;
        const upstreamIndex = typeof call.index === 'number' ? call.index : toolIndexes.size;
        let index = toolIndexes.get(upstreamIndex);
        if (index === undefined) {
          if (textIndex !== -1) {
            out.push(sseEvent('content_block_stop', { type: 'content_block_stop', index: textIndex }));
            textIndex = -1;
          }
          index = nextIndex;
          nextIndex += 1;
          toolIndexes.set(upstreamIndex, index);
          const fn = isRecord(call.function) ? call.function : {};
          out.push(
            sseEvent('content_block_start', {
              type: 'content_block_start',
              index,
              content_block: {
                type: 'tool_use',
                id: typeof call.id === 'string' && call.id !== '' ? call.id : `toolu_${index}`,
                name: typeof fn.name === 'string' ? fn.name : '',
                input: {},
              },
            }),
          );
        }
        const fn = isRecord(call.function) ? call.function : {};
        if (typeof fn.arguments === 'string' && fn.arguments !== '') {
          out.push(sseEvent('content_block_delta', { type: 'content_block_delta', index, delta: { type: 'input_json_delta', partial_json: fn.arguments } }));
        }
      }
      if (choice.finish_reason !== null && choice.finish_reason !== undefined) pendingStop = stopReasonOf(choice.finish_reason);
    }
    return out;
  };

  try {
    for (;;) {
      const { value, done } = await reader.read();
      if (done) break;
      buffer += decoder.decode(value, { stream: true }).replace(/\r\n/g, '\n');
      let at = buffer.indexOf('\n\n');
      while (at !== -1) {
        const frame = buffer.slice(0, at);
        buffer = buffer.slice(at + 2);
        for (const event of eventsOfFrame(frame)) yield event;
        at = buffer.indexOf('\n\n');
      }
    }
    buffer += decoder.decode();
    if (buffer.trim() !== '') for (const event of eventsOfFrame(buffer)) yield event;
  } finally {
    reader.releaseLock();
  }
  if (!finished) {
    for (const event of startEvents()) yield event;
    for (const event of finishEvents(pendingStop ?? 'end_turn')) yield event;
  }
}

// ---------------------------------------------------------------------------
// Routing with rating order, one retry, failover and per-model cooldown.
// ---------------------------------------------------------------------------

/** Models that refused in this trial: never spend another call on one. */
const cooledDown = new Set<string>();

/** Eligible free models for a request, best rating first, brief order breaking ties. */
function rankedCandidates(requires: Requirement): ModelRow[] {
  return freeList
    .filter((m) => !cooledDown.has(m.id) && meetsRequirements(requires, capabilitiesOf(m)))
    .sort((a, b) => b.rating_milli - a.rating_milli);
}

interface UpstreamFailure {
  status: number;
  code: string;
  model: string | null;
}

interface DialOutcome {
  ok: true;
  model: string;
  response: Response;
  failures: UpstreamFailure[];
}

interface DialFailure {
  ok: false;
  failures: UpstreamFailure[];
}

function failureCode(status: number, text: string): string {
  try {
    const parsed: unknown = JSON.parse(text);
    if (isRecord(parsed) && isRecord(parsed.error) && typeof parsed.error.code === 'string') return parsed.error.code;
    if (isRecord(parsed) && typeof parsed.code === 'string') return parsed.code;
  } catch {
    // Not JSON: fall through to the status.
  }
  if (status === 400) return 'model_not_allowed';
  if (status === 401) return 'unauthorized';
  if (status === 429) return 'rate_limited';
  if (status >= 500) return 'upstream_error';
  return `http_${status}`;
}

function chatCompletionsUrl(): string {
  if (GATEWAY_URL === '') return '';
  return GATEWAY_URL.endsWith('/v1') ? `${GATEWAY_URL}/chat/completions` : `${GATEWAY_URL}/v1/chat/completions`;
}

async function dialOnce(model: string, body: Json): Promise<Response> {
  const headers: Record<string, string> = {
    'content-type': 'application/json',
    authorization: `Bearer ${GATEWAY_KEY}`,
  };
  if (body.stream === true) headers.accept = 'text/event-stream';
  return fetch(chatCompletionsUrl(), {
    method: 'POST',
    headers,
    body: JSON.stringify({ ...body, model }),
    signal: AbortSignal.timeout(DIAL_TIMEOUT_MS),
  });
}

/**
 * Dial the prompt's models in rating order until one answers. The first model that
 * refuses gets one retry after a short pause (a burst rate limit may clear); every
 * refusal cools its model down for the trial and is recorded for the
 * x-makefun-upstream-failures trail.
 */
async function dialWithFailover(requires: Requirement, body: Json): Promise<DialOutcome | DialFailure> {
  const failures: UpstreamFailure[] = [];
  const tried = new Set<string>();
  let calls = 0;
  let retried = false;
  for (;;) {
    if (calls >= MAX_CALLS_PER_PROMPT) return { ok: false, failures };
    const next = rankedCandidates(requires).find((m) => !tried.has(m.id)) ?? null;
    if (next === null) return { ok: false, failures };
    calls += 1;
    let response: Response;
    try {
      response = await dialOnce(next.id, body);
    } catch (err) {
      const code = err instanceof Error && err.name === 'TimeoutError' ? 'timeout' : 'upstream_unreachable';
      failures.push({ status: 502, code, model: next.id });
      cooledDown.add(next.id);
      tried.add(next.id);
      // A dropped call may be transient: one retry of the first model that refused.
      if (!retried && calls < MAX_CALLS_PER_PROMPT) {
        retried = true;
        cooledDown.delete(next.id);
        tried.delete(next.id);
        await sleep(RETRY_PAUSE_MS);
      }
      continue;
    }
    if (response.ok && response.body !== null) return { ok: true, model: next.id, response, failures };
    const text = await response.text().catch(() => '');
    failures.push({ status: response.status, code: failureCode(response.status, text), model: next.id });
    cooledDown.add(next.id);
    tried.add(next.id);
    // Only a refusal that may clear gets a retry: a rate limit, a 5xx, a timeout.
    // A 4xx permission refusal (401/403) is deterministic for the key, so retrying
    // it only burns a call: fail over to the next model at once.
    const retryable = response.status === 429 || response.status >= 500;
    if (retryable && !retried && calls < MAX_CALLS_PER_PROMPT) {
      retried = true;
      cooledDown.delete(next.id);
      tried.delete(next.id);
      await sleep(RETRY_PAUSE_MS);
    }
  }
}

